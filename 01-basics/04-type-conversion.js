// String to Number
let age = "22";
let convertedAge = Number(age);

console.log(convertedAge);
console.log(typeof convertedAge);

// Number to String
let score = 100;
let convertedScore = String(score);

console.log(convertedScore);
console.log(typeof convertedScore);

// Boolean conversion
console.log(Boolean(1));
console.log(Boolean(0));
console.log(Boolean("Hello"));
console.log(Boolean(""));

// Implicit conversion
console.log("10" + 5);
console.log("10" - 5);